"""Master-data records and the Model getters that just read them.

    python3 scripts/engine/gen_records.py

1. For every ReDriveBattleCore.Model.*MstModel, the record class it wraps (Network.Definition.*.*MstRecord) is read
   from dump.cs and written as a TS interface to src/engine/Network/Definition/<ns>/<Record>.ts (field names are the
   JSON keys of src/assets/base_data/get<Name>MstList.json; the first field, at 0x10, is the unique key).
   A table of all of them goes to src/engine/records.json (consumed by src/engine/adapter/MasterData.ts).
2. Model getters whose machine code is `rax = this.record (+0x10); return rax->field` are filled in
   (`return this.record.field; /* asm */`), `any /* XMstRecord */` types are replaced by the interface.
"""
import json, os, re, struct, sys
import capstone

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
ENG = os.path.join(ROOT, 'src', 'engine')
UNP = os.environ.get('XQ_UNPACKED') or os.path.normpath(os.path.join(ROOT, '..', 'unpackedExedra'))
DUMPER = os.environ.get('XQ_DUMPER') or os.path.normpath(os.path.join(ROOT, '..', 'Il2CppDumper'))
VER = os.environ.get('XQ_GAME_VER', '3.19.0')
dump = open(os.path.join(DUMPER, 'dump.cs'), encoding='utf-8', errors='ignore').read()
d = open(os.path.join(UNP, VER, 'GameAssembly.unpack.dll'), 'rb').read()
pe = struct.unpack_from('<I', d, 0x3C)[0]; n = struct.unpack_from('<H', d, pe + 6)[0]; opt = struct.unpack_from('<H', d, pe + 20)[0]
o = pe + 24 + opt; secs = []
for _ in range(n):
    vs, va, rs, ra = struct.unpack_from('<IIII', d, o + 8); o += 40; secs.append((va, max(vs, rs), ra))
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)


def insns(r, k=10):
    off = next(r - va + ra for va, sz, ra in secs if va <= r < va + sz)
    out = []
    for i in md.disasm(d[off:off + 80], r):
        out.append((i.mnemonic, i.op_str))
        if i.mnemonic in ('ret', 'jmp') or len(out) >= k: break
    return out


TS = {'int': 'int', 'long': 'long', 'float': 'float', 'double': 'double', 'bool': 'boolean', 'string': 'string',
      'short': 'short', 'byte': 'byte'}
mdir = os.path.join(ENG, 'ReDriveBattleCore', 'Model')
table = {}
for f in sorted(os.listdir(mdir)):
    if not f.endswith('MstModel.ts'): continue
    mdl = f[:-3]; rec = mdl.replace('MstModel', 'MstRecord')
    m = re.search(r'\n// Namespace: (\S+)\n(?:\[[^\n]*\]\n)*public class ' + rec + r' : [^\n]*? // TypeDefIndex: \d+\n\{(.*?)\n\}\n', dump, re.S)
    if not m: sys.exit('no record ' + rec)
    ns, body = m.group(1), m.group(2)
    fields = [(fm.group(2), fm.group(1).strip(), int(fm.group(3), 16))
              for fm in re.finditer(r'private ([^\n]*?) <(\w+)>k__BackingField; // (0x[0-9A-F]+)', body)]
    fname = 'get' + rec.replace('MstRecord', '') + 'MstList.json'
    table[mdl] = {'record': rec, 'file': fname, 'key': next(x[0] for x in fields if x[2] == 0x10),
                  'fields': [x[0] for x in fields]}
    out = os.path.join(ENG, *ns.split('.'), rec + '.ts')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    lines = ['// Master-data record (outside ReDriveBattleCore): ' + ns + '.' + rec + ', generated by scripts/engine/gen_records.py.',
             '// One row of src/assets/base_data/' + fname + ' (same keys).', '']
    rt = sorted({TS[t] for _, t, _ in fields if TS.get(t) in ('int', 'long', 'float', 'double', 'short', 'byte')})
    if rt:
        rel = os.path.relpath(os.path.join(ENG, 'runtime'), os.path.dirname(out)).replace(os.sep, '/')
        lines.append(f'import type {{ {", ".join(rt)} }} from "{rel}";')
        lines.append('')
    lines.append(f'export interface {rec} {{')
    for nm, t, off in fields:
        lines.append(f'    /** {off:#x} {t} */')
        lines.append(f'    {nm}: {TS.get(t, "any")};')
    lines.append('}')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    # model file: type + getters
    path = os.path.join(mdir, f)
    src = open(path, encoding='utf-8').read()
    rel = os.path.relpath(out[:-3], mdir).replace(os.sep, '/')
    if f'any /* {rec} */' in src:
        src = src.replace(f'any /* {rec} */', rec)
        src = src.replace('\n\n// ----', f'\nimport type {{ {rec} }} from "{rel}";\n\n// ----', 1)
    offmap = {off: nm for nm, t, off in fields}
    cnt = 0

    def fill(mm):
        global cnt
        ind, decl, rva = mm.group(1), mm.group(2), int(mm.group(3), 16)
        ins = insns(rva)
        if len(ins) < 3: return mm.group(0)
        src_reg = None; i = 0
        if ins[0][0] == 'sub': i = 1
        if ins[i] != ('mov', 'rax, qword ptr [rcx + 0x10]'): return mm.group(0)
        i += 1
        if ins[i][0] == 'test': i += 2  # test + je
        if i >= len(ins): return mm.group(0)
        op, args = ins[i]
        lm = re.match(r'(?:eax|rax|al|xmm0), (?:byte |dword |qword )?(?:ptr )?\[rax \+ (0x[0-9a-f]+)\]', args)
        if op not in ('mov', 'movzx', 'movss', 'movsxd') or not lm: return mm.group(0)
        rest = [x[0] for x in ins[i + 1:]]
        if rest not in (['add', 'ret'], ['ret']): return mm.group(0)
        fld = offmap.get(int(lm.group(1), 16))
        if not fld: return mm.group(0)
        ret = decl.rsplit('): ', 1)[1]
        cast = '' if ret in ('int', 'string', 'boolean', 'float', 'long') else f' as {ret}'
        if ret == 'boolean' and dict((a, b) for a, b, c in fields)[fld] != 'bool': return mm.group(0)
        cnt += 1
        asm = '; '.join((a + ' ' + b).strip() for a, b in ins)
        return f'{ind}{decl} {{ return this.record.{fld}{cast}; /* asm: {asm} */ }}'
    src = re.sub(r'^(\s+)((?!static )get_\w+\(\): .+?) \{ return notPorted\("[^"]*", (0x[0-9A-F]+)\); \}$', fill, src, flags=re.M)
    open(path, 'w', encoding='utf-8', newline='\n').write(src)
    print(f'{mdl}: {cnt} getters')
json.dump(table, open(os.path.join(ENG, 'records.json'), 'w'), indent=1)
